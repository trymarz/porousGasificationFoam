#!/bin/bash
# pack.sh — pgf pack: a self-contained Apptainer image of one PGF commit (#264
# PR 6). Source-only; needs PGF_ROOT and coupling.sh. The image compiles the
# pinned Foam-Yade and PGF itself, so nothing from the host build is copied.

PGF_PACK_BASE_DEF="container/pgf-toolchain.def"

# Build dependencies of a headless yade on the toolchain image (Ubuntu 24.04).
PGF_PACK_YADE_DEPS="cmake git g++ python3-dev python3-numpy python3-mpi4py python3-mpmath \
python3-matplotlib python3-ipython python3-pygraphviz python3-xlib python3-sphinx python3-tk libboost-all-dev libeigen3-dev libgts-dev libcgal-dev \
libvtk9-dev libsqlite3-dev libbz2-dev zlib1g-dev libopenblas-dev libsuitesparse-dev \
libmetis-dev coinor-libclp-dev libmpfr-dev libmpfrc++-dev libmpc-dev libloki-dev"

pgf_pack_usage() {
  cat <<'EOF'
usage: pgf pack [BUILD] [--no-yade] [--output FILE] [--dry-run]
  BUILD      a build (key, key prefix, commit or worktree; see pgf builds) whose
             commit to pack; default: this checkout's HEAD, which must be clean
  --no-yade  pack the yade0 variant (no yade in the image)
  --output   the .sif to write (default ./pgf-<commit12>-yade<0|1>.sif)
  --dry-run  write the build context and print the definition; build nothing
EOF
}

# pgf_pack_from — the base image line of the toolchain definition.
pgf_pack_from() {
  grep -m1 '^From:' "$PGF_ROOT/$PGF_PACK_BASE_DEF" | sed 's/^From:[[:space:]]*//'
}

# pgf_pack_def COMMIT VARIANT PIN API YADE_VERSION — the image definition.
pgf_pack_def() {
  local commit="$1" variant="$2" pin="$3" api="$4" yver="$5" build_flag=""
  [ "$variant" = yade1 ] && build_flag="--yade"
  cat <<EOF
# Generated by pgf pack for porousGasificationFoam ${commit:0:12} ($variant).
Bootstrap: docker
From: $(pgf_pack_from)

%files
    pgf-src.tar /opt/pgf/pgf-src.tar
EOF
  [ "$variant" = yade1 ] && echo "    foam-yade.tar /opt/pgf/foam-yade.tar"
  cat <<EOF

%post
    set -eu
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -q
    apt-get install -y --no-install-recommends python3$( [ "$variant" = yade1 ] && echo " $PGF_PACK_YADE_DEPS")
    mkdir -p /opt/pgf/src && tar -xf /opt/pgf/pgf-src.tar -C /opt/pgf/src && rm /opt/pgf/pgf-src.tar
EOF
  if [ "$variant" = yade1 ]; then
    cat <<EOF
    mkdir -p /opt/pgf/foam-yade /tmp/yade-build && tar -xf /opt/pgf/foam-yade.tar -C /opt/pgf/foam-yade && rm /opt/pgf/foam-yade.tar
    cd /tmp/yade-build
    cmake /opt/pgf/foam-yade -DCMAKE_INSTALL_PREFIX=/opt/yade -DENABLE_GUI=OFF -DNOSUFFIX=ON \\
        -DYADE_VERSION=$yver -DCMAKE_BUILD_TYPE=Release
    make -j"\$(nproc)" install
    cd / && rm -rf /tmp/yade-build
    export YADE_BIN=/opt/yade/bin/yade YADE_TRUNK=/opt/pgf/foam-yade
EOF
  fi
  cat <<EOF
    export PGF_FOAM_BASHRC="\$(ls -d /usr/lib/openfoam/openfoam*/etc/bashrc | head -1)"
    export PGF_BUILD_ROOT=/opt/pgf/builds HOME=/root
    /opt/pgf/src/pgf build $build_flag
    key="\$(ls /opt/pgf/builds | grep -v '^\.' | grep -v '\.lock\$' | head -1)"
    python3 - "\$key" <<'PY'
import json, subprocess, sys
sh = lambda c: subprocess.run(c, shell=True, capture_output=True, text=True).stdout.strip()
m = {"pgf_commit": "$commit", "variant": "$variant", "build_key": sys.argv[1],
     "foam_yade_pin": "$pin" or None, "foam_yade_api_hash": "$api" or None,
     "base_image": "$(pgf_pack_from)", "gcc": sh("gcc -dumpfullversion"),
     "os": sh(". /etc/os-release && echo \$PRETTY_NAME")}
json.dump(m, open("/opt/pgf/manifest.json", "w"), indent=2)
PY
    chmod -R a+rX /opt/pgf

%environment
    export PGF_FOAM_BASHRC="\$(ls -d /usr/lib/openfoam/openfoam*/etc/bashrc | head -1)"
    export PGF_BUILD_ROOT=/opt/pgf/builds PGF_IMAGE_MANIFEST=/opt/pgf/manifest.json
    export PATH="/opt/pgf/src:\$PATH"
EOF
  [ "$variant" = yade1 ] && echo '    export YADE_BIN=/opt/yade/bin/yade YADE_TRUNK=/opt/pgf/foam-yade'
  cat <<'EOF'

%runscript
    # apptainer run IMAGE ./Allrun runs the case in the current directory.
    case "${1:-status}" in
    status | doctor | exec | shell | run | builds | ls) exec /opt/pgf/src/pgf "${@:-status}" ;;
    esac
    exec /opt/pgf/src/pgf run "$PWD" "$@"

%labels
    Manifest /opt/pgf/manifest.json
EOF
}

pgf_pack_cmd() {
  local sel="" variant=yade1 out="" dry=0 commit meta trunk pin api ctx yver dirty
  while [ $# -gt 0 ]; do
    case "$1" in
    --no-yade) variant=yade0 ;;
    --yade) variant=yade1 ;;
    --dry-run) dry=1 ;;
    --output) out="${2:?--output needs a file}"; shift ;;
    -h | --help) pgf_pack_usage; return 0 ;;
    -*) echo "pgf pack: unknown option $1" >&2; pgf_pack_usage >&2; return 2 ;;
    *) sel="$1" ;;
    esac
    shift
  done
  git -C "$PGF_ROOT" rev-parse --git-dir >/dev/null 2>&1 || { echo "pgf pack: $PGF_ROOT is not a git checkout" >&2; return 2; }
  if [ -n "$sel" ]; then
    meta="$(python3 "$PGF_LIB/registry.py" resolve "${PGF_BUILD_ROOT:?}" "$variant" "$sel")" || return 2
    read -r commit variant dirty < <(python3 -c 'import json,sys; m=json.load(open(sys.argv[1]))
print(m.get("git_head") or "-", m.get("variant") or "-", int(bool((m.get("checkout") or {}).get("dirty"))))' "$meta/.pgf-build.json")
    [ "$dirty" = 0 ] || { echo "pgf pack: $meta was built from a dirty tree; its sources have no commit to pack" >&2; return 2; }
  else
    commit="$(git -C "$PGF_ROOT" rev-parse HEAD)"
    [ -z "$(git -C "$PGF_ROOT" status --porcelain --untracked-files=no --ignore-submodules=all)" ] ||
      { echo "pgf pack: this checkout has uncommitted changes; commit them or name a BUILD" >&2; return 2; }
  fi
  git -C "$PGF_ROOT" cat-file -e "$commit^{commit}" 2>/dev/null || { echo "pgf pack: commit $commit is not in this repository" >&2; return 2; }
  pin="$(git -C "$PGF_ROOT" ls-tree "$commit" submodules/Foam-Yade | awk '$2 == "commit" {print $3}')"
  ctx="${PGF_PACK_DIR:-${TMPDIR:-/tmp}/pgf-pack-${commit:0:12}-$variant}"
  out="${out:-$PWD/pgf-${commit:0:12}-$variant.sif}"
  mkdir -p "$ctx" || return 2
  git -C "$PGF_ROOT" archive --format=tar -o "$ctx/pgf-src.tar" "$commit" || return 2
  if [ "$variant" = yade1 ]; then
    [ -n "$pin" ] || { echo "pgf pack: $commit pins no Foam-Yade submodule" >&2; return 2; }
    for trunk in "${YADE_TRUNK:-}" "$PGF_ROOT/submodules/Foam-Yade"; do
      [ -n "$trunk" ] && git -C "$trunk" cat-file -e "$pin^{commit}" 2>/dev/null && break
      trunk=""
    done
    [ -n "$trunk" ] || { echo "pgf pack: the Foam-Yade pin $pin is in neither YADE_TRUNK nor the submodule" >&2; return 2; }
    git -C "$trunk" archive --format=tar -o "$ctx/foam-yade.tar" "$pin" || return 2
    api="$(pgf_coupling_api_hash_at "$trunk" "$pin")"
    yver="$(git -C "$trunk" show -s --format=%cd --date=format:%Y.%m.%d "$pin")-git-${pin:0:7}"
  fi
  pgf_pack_def "$commit" "$variant" "$pin" "$api" "$yver" >"$ctx/pgf-pack.def" || return 2
  echo "pgf pack: ${commit:0:12} $variant${pin:+, Foam-Yade ${pin:0:10}}; context $ctx" >&2
  if [ "$dry" -eq 1 ]; then
    cat "$ctx/pgf-pack.def"
    echo "pgf pack: dry run; would build $out with: (cd $ctx && apptainer build --fakeroot --ignore-subuid $out pgf-pack.def)" >&2
    return 0
  fi
  command -v apptainer >/dev/null || { echo "pgf pack: apptainer not found" >&2; return 2; }
  (cd "$ctx" && apptainer build --fakeroot --ignore-subuid "$out" pgf-pack.def) || return 1
  echo "pgf pack: wrote $out" >&2
}
